/**
 * Pickory Product Filter — Production Export Script
 *
 * Usage:
 *   npm run export:production
 */

import fs from "fs";
import path from "path";
import { execSync } from "child_process";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const PLUGIN_ROOT = path.resolve(__dirname, "..");
const DIST_PRODUCTION_DIR = path.join(PLUGIN_ROOT, "dist-production");
const TARGET_DIR = path.join(DIST_PRODUCTION_DIR, "pickory-product-filter");
const DIST_IGNORE_PATH = path.join(PLUGIN_ROOT, ".distignore");
const MANIFEST_PATH = path.join(PLUGIN_ROOT, "build", ".vite", "manifest.json");

/**
 * Check if directory is empty
 */
function isDirEmpty(dirPath) {
  try {
    const files = fs.readdirSync(dirPath);
    return files.length === 0;
  } catch {
    return true;
  }
}

/**
 * Read .distignore and parse into regex patterns
 */
function readDistignore() {
  const ignorePatterns = [];
  if (!fs.existsSync(DIST_IGNORE_PATH)) {
    return ignorePatterns;
  }
  const content = fs.readFileSync(DIST_IGNORE_PATH, "utf8");
  const lines = content.split(/\r?\n/);
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) {
      continue;
    }
    let pattern = trimmed;
    // Convert glob to regex
    let regexPattern = pattern
      .replace(/\./g, "\\.")
      .replace(/\*/g, "[^/\\\\]*")
      .replace(/\?/g, "[^/\\\\]");
    if (regexPattern.endsWith("/")) {
      regexPattern = regexPattern.slice(0, -1) + "(\\/.*)?";
    } else if (!regexPattern.includes("/")) {
      regexPattern = ".*(\\/|\\\\)?" + regexPattern;
    }
    if (!regexPattern.startsWith(".*")) {
      regexPattern = "^" + regexPattern;
    }
    ignorePatterns.push(new RegExp(regexPattern, "i"));
  }
  return ignorePatterns;
}

/**
 * Check if a file should be ignored
 */
function shouldIgnore(filePath, ignorePatterns) {
  const relative = path.relative(PLUGIN_ROOT, filePath);
  const normalized = relative.replace(/\\/g, "/");
  for (const pattern of ignorePatterns) {
    if (pattern.test(normalized)) {
      return true;
    }
  }
  return false;
}

/**
 * Recursively copy files, respecting ignore patterns
 */
function copyFiles(src, dest, ignorePatterns) {
  let filesCopied = 0;
  if (!fs.existsSync(dest)) {
    fs.mkdirSync(dest, { recursive: true });
  }
  const entries = fs.readdirSync(src, { withFileTypes: true });
  for (const entry of entries) {
    const srcPath = path.join(src, entry.name);
    const destPath = path.join(dest, entry.name);
    if (shouldIgnore(srcPath, ignorePatterns)) {
      continue;
    }
    if (entry.isDirectory()) {
      filesCopied += copyFiles(srcPath, destPath, ignorePatterns);
    } else {
      fs.copyFileSync(srcPath, destPath);
      filesCopied++;
    }
  }
  return filesCopied;
}

// ─── Step 1: Fresh Vite build ────────────────────────────────────────────────
console.log("\n🚀 Pickory Product Filter Production Export 🚀\n");
console.log("📦 Step 1: Building fresh Vite assets...");
execSync("npm run build", { cwd: PLUGIN_ROOT, stdio: "inherit" });

if (!fs.existsSync(MANIFEST_PATH)) {
  console.error(
    "\n❌ FATAL: build/.vite/manifest.json was not generated by the build.\n",
  );
  process.exit(1);
}
console.log("✅ Vite build succeeded and manifest found.\n");

// ─── Step 2: Validate build folder ────────────────────────────────────────────
console.log("🔍 Step 2: Validating...");
const buildPath = path.join(PLUGIN_ROOT, "build");
if (!fs.existsSync(buildPath) || isDirEmpty(buildPath)) {
  console.error("❌ Validation failed: build/ folder is missing or empty!");
  process.exit(1);
}
console.log("✅ build/ folder exists and is not empty");

// ─── Step 3: Clean and prepare target directory ─────────────────────────────────
console.log("\n📁 Step 3: Preparing export...");
if (fs.existsSync(DIST_PRODUCTION_DIR)) {
  fs.rmSync(DIST_PRODUCTION_DIR, { recursive: true, force: true });
}
fs.mkdirSync(DIST_PRODUCTION_DIR, { recursive: true });
fs.mkdirSync(TARGET_DIR, { recursive: true });

// ─── Step 4: Copy filtered files ──────────────────────────────────────────────
const ignorePatterns = readDistignore();
const totalFiles = copyFiles(PLUGIN_ROOT, TARGET_DIR, ignorePatterns);
console.log(`✅ Copied ${totalFiles} files to temp folder\n`);

// ─── Step 5: Validation ───────────────────────────────────────────────────────
console.log("🔍 Step 4: Validating export...");

const forbiddenDirs = [
  "node_modules",
  "vendor",
  "scripts",
  "tests",
  "documentation",
  ".vscode",
  ".idea",
  ".cursor",
  "scratch",
  "plugin reports",
];

let hasErrors = false;

for (const dir of forbiddenDirs) {
  if (fs.existsSync(path.join(TARGET_DIR, dir))) {
    console.error(`❌ ERROR: Forbidden directory found in export: ${dir}`);
    hasErrors = true;
  }
}

// Confirm the build folder and manifest made it in
const exportedManifest = path.join(
  TARGET_DIR,
  "build",
  ".vite",
  "manifest.json",
);
if (!fs.existsSync(exportedManifest)) {
  console.error(
    "❌ ERROR: build/.vite/manifest.json is missing from the export.",
  );
  hasErrors = true;
} else {
  console.log("✅ build manifest present.");
}

// Confirm main plugin file is present
const mainPlugin = path.join(TARGET_DIR, "pickory-product-filter.php");
if (!fs.existsSync(mainPlugin)) {
  console.error("❌ ERROR: pickory-product-filter.php is missing from the export.");
  hasErrors = true;
} else {
  console.log("✅ pickory-product-filter.php present.");
}

if (hasErrors) {
  console.error(
    "\n❌ FATAL: Export validation failed. Please fix the issues above.",
  );
  process.exit(1);
}

console.log("\n✅ All validation checks passed!");

// Summary
console.log("\n✅ Export completed successfully!");
console.log("------------------------------------");
console.log(`📦 Total files: ${totalFiles}`);
console.log(`📂 Output: ${TARGET_DIR}`);
console.log("------------------------------------");
console.log("\nNext step: Run \"npm run zip\" to create the ZIP file!\n");
